import { test, expect } from '@playwright/test'

test('store filters, duplicate adds and demo order work together', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.product-card')).toHaveCount(20)
  await page.getByRole('searchbox', { name: 'Search products' }).fill('Pebble')
  await page.getByRole('checkbox', { name: 'In stock only' }).check()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear filters' }).click()
  const add = page.getByRole('button', { name: 'Add Studio Wireless to bag' })
  await add.click()
  await add.click()
  await expect(page.getByTestId('cart-row')).toHaveCount(1)
  await expect(page.getByLabel('Quantity for Studio Wireless')).toHaveText('2')
  await expect(page.locator('.cart-total')).toContainText('Rs. 6,298.20')
  await page.getByRole('button', { name: 'Review order' }).click()
  await page.getByRole('button', { name: 'Place demo order' }).click()
  await expect(page.getByRole('dialog')).toContainText('Your demo order has been placed.')
  const back = page.getByRole('button', { name: 'Back to the collection' })
  await expect(back).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Your bag' })).toBeFocused()
  await expect(page.getByTestId('cart-row')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('all store load states can be demonstrated and retry restores products', async ({ page }) => {
  await page.goto('/?state=slow')
  await expect(page.getByRole('status', { name: 'Loading products' })).toBeVisible()
  await expect(page.locator('.product-card')).toHaveCount(20)
  await page.goto('/?state=empty')
  await expect(page.getByText('Something good is coming.')).toBeVisible()
  await page.goto('/?state=error')
  await expect(page.getByRole('alert')).toContainText('A small interruption.')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.locator('.product-card')).toHaveCount(20)
})

test('customer modal validates, traps focus, saves once, restores focus and exports matching rows', async ({
  page,
}) => {
  await page.goto('/customers')
  await expect(page.locator('tbody tr')).toHaveCount(8)
  const trigger = page.getByRole('button', { name: 'Add customer' })
  await trigger.click()
  await expect(page.getByLabel('Full name')).toBeFocused()
  await page.getByRole('button', { name: 'Add customer', exact: true }).last().click()
  await expect(page.getByRole('alert')).toHaveCount(3)
  await page.getByLabel('Full name').fill('Test Customer')
  await page.getByLabel('Email address').fill('test.customer@example.com')
  await page.getByLabel('City', { exact: true }).fill('Karachi')
  const submit = page.getByRole('dialog').getByRole('button', { name: 'Add customer' })
  await submit.focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close dialog' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(submit).toBeFocused()
  await submit.click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(page.locator('tbody tr')).toHaveCount(9)
  await page.getByRole('searchbox', { name: 'Search customers' }).fill('test.customer')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: 'Export customers' }).click()
  await expect(page.getByText('Getting your customer export ready…')).toBeVisible()
  await expect(page.getByText('Your export is ready.')).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download CSV' }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('form-customers.csv')
  await page.getByRole('link', { name: 'View Test Customer' }).click()
  await expect(page.locator('.profile-card h2')).toHaveText('Test Customer')
})

test('customer detail cancels stale requests and works after direct refresh', async ({ page }) => {
  await page.goto('/customers/c01')
  await page.getByRole('link', { name: 'Next customer' }).click()
  await expect(page.locator('.profile-card h2')).toHaveText('Omar Farooq')
  await page.waitForTimeout(1200)
  await expect(page.locator('.profile-card h2')).toHaveText('Omar Farooq')
  await page.reload()
  await expect(page.locator('.profile-card h2')).toHaveText('Omar Farooq')
  await page.goto('/customers/missing')
  await expect(page.getByText('This connection isn’t here.')).toBeVisible()
})

test('dashboard error, empty and failed export paths are recoverable', async ({ page }) => {
  await page.goto('/customers?state=empty')
  await expect(page.getByText('Your community starts here.')).toBeVisible()
  await page.goto('/customers?state=error')
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await page.goto('/customers?exportError=1')
  await page.getByRole('button', { name: 'Export customers' }).click()
  await expect(page.getByText('The export couldn’t be prepared.')).toBeVisible()
  await expect(page.locator('.export-banner svg.lucide-circle-alert')).toBeVisible()
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByText('Getting your customer export ready…')).toBeVisible()
  await expect(page.getByText('Your export is ready.')).toBeVisible()
  await expect(page).not.toHaveURL(/exportError/)
})

for (const width of [390, 768, 1024, 1440]) {
  test(`layouts at ${width}px have no page overflow`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 })
    for (const route of ['/', '/customers', '/customers/c02', '/project']) {
      await page.goto(route)
      if (route === '/') await expect(page.locator('.product-card')).toHaveCount(20)
      if (route === '/customers') await expect(page.locator('tbody tr')).toHaveCount(8)
      if (route === '/customers/c02')
        await expect(page.locator('.profile-card h2')).toHaveText('Omar Farooq')
      const overflow = await page.evaluate(
        () => document.documentElement.scrollWidth > window.innerWidth,
      )
      expect(overflow, `${route} at ${width}px`).toBe(false)
    }
  })
}
